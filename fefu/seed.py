def seed_if_empty(db):
    if db.execute("SELECT COUNT(*) FROM products").fetchone()[0]:
        return False
    now = time.time()
    db.execute("BEGIN IMMEDIATE")
    try:
        for i, (icon, name, cat, price, stock, desc, stars, author, review) in enumerate(PRODUCTS):
            cur = db.execute(
                "INSERT INTO products(name, icon, category, description, price, stock, created_at)"
                " VALUES (?,?,?,?,?,?,?)",
                (name, icon, cat, desc, price, stock, now + i),
            )
            db.execute(
                "INSERT INTO reviews(product_id, user_id, author, rating, body, created_at)"
                " VALUES (?,NULL,?,?,?,?)",
                (cur.lastrowid, author, stars, review, now - (len(PRODUCTS) - i) * 3600),
            )
        db.execute("COMMIT")
    except BaseException:
        db.execute("ROLLBACK")
        raise
    return True
